import { createRequire } from 'module'; const { chromium } = createRequire('/opt/npm-tools/node_modules/')('playwright');
const base = process.env.BASE || 'http://localhost:3100';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' }).catch(() => chromium.launch());
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const txt = async (s) => (await p.locator(s).first().innerText()).trim();
const next = () => p.click('[data-next]');
await p.goto(base + '/reservation/');
await p.check('input[name=event_type][value=mariage]', { force: true }); await next();
await p.fill('#event_address', '10 rue de Rivoli, Paris'); await p.check('input[name=installation_type][value=indoor]', { force: true }); await next();
await p.check('input[name=photobooth_requested][value=yes]', { force: true });
console.log('modèle visible:', await p.locator('[data-field=photobooth_model]').isVisible());
await next(); console.log('erreur sans modèle:', await txt('[data-summary]'));
await p.screenshot({ path: '/tmp/booth-step3.png', fullPage: true });
await p.check('input[name=photobooth_model][value=bois]', { force: true });
await next();
console.log('étape:', await txt('[data-progress-name]'), '| cartes:', await p.locator('[data-packages] input').count());
console.log('première carte:', (await p.locator('[data-packages] label').first().innerText()).replace(/\n+/g, ' '));
await p.screenshot({ path: '/tmp/booth-step4.png', fullPage: true });
await p.locator('[data-packages] input').first().check({ force: true });
await p.click('[data-prev]'); await p.check('input[name=photobooth_model][value=classique]', { force: true }); await next();
console.log('classique cartes:', await p.locator('[data-packages] input').count(), '| coché:', await p.locator('[data-packages] input:checked').count());
await p.goto(base + '/prestations/'); 
console.log('prestations bois visible:', await p.locator('[data-booth-panel=bois]').isVisible(), '| classique caché:', !(await p.locator('[data-booth-panel=classique]').isVisible()));
await p.click('#tab-classique');
console.log('après clic classique:', await p.locator('[data-booth-panel=classique]').isVisible());
await p.screenshot({ path: '/tmp/booth-prestations.png', fullPage: true });
console.log('JS errors:', errs);
await b.close();
